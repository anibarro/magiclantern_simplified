#!/usr/bin/env python3
"""Generates modules/livecomp/raw14-add-asm.h (LCM65 Live Bulb add and
dark-frame subtract kernels in ARM assembly). Run it after changing the
tables; the result is committed."""
# Per field, like lc_raw14_add_sel, ARMv5TE, words loaded with LDM.
P=[[0,14,28],[10,24],[6,20],[2,16,30],[12,26],[8,22],[4,18]]   # field start offsets (from MSB) per stream word
def regnum(r): return int(r[1:]) if r!='lr' else 14
def gen(sub):
    # r0 d, r1 s, r2 F=0x3FFF, r3 black, r4 white, r5-r7 d words, r8-r10 s words,
    # r11 a, r12 b / result, lr output word (stream order); [sp] end of d.
    L=[];A=L.append
    A("push {r4-r11,lr}")
    A("cmp r2,#0");A("beq 9f")
    A("ldr r4,[sp,#36]")                                        # white (5th argument)
    A("mov r12,r2,lsl #5");A("sub r12,r12,r2,lsl #2");A("add r12,r0,r12");A("str r12,[sp,#-4]!")
    A("mov r2,#0x3F00");A("orr r2,r2,#0xFF")
    A("cmp r4,r2");A("movhi r4,r2")                             # w = min(white, 16383)
    A("1:")
    free={'d':['r5','r6','r7'],'s':['r8','r9','r10']};reg={'d':{},'s':{}};base={'d':'r0','s':'r1'}
    off=0
    def load(words):
        nonlocal off
        for b in ('d','s'):
            rs=sorted(free[b][:len(words)],key=regnum);free[b]=free[b][len(words):]
            for w,r in zip(words,rs): reg[b][w]=r
            if len(rs)==2: A(f"ldmia {base[b]}!,{{{rs[0]},{rs[1]}}}")
            else: A(f"ldr {rs[0]},[{base[b]}],#4")
        off+=4*len(words)
    def field(dst,b,i,p):
        W=reg[b][i]
        if p<=18:
            r=(34-p)%32                                         # ror16 (stream order) then >>(18-p)
            A(f"and {dst},r2,{W},ror #{r}" if r else f"and {dst},r2,{W}")
        else:
            N=reg[b][i+1]                                       # low half of W, high half of N
            A(f"mov {dst},{W},lsr #16");A(f"orr {dst},{dst},{N},lsl #16");A(f"and {dst},r2,{dst},ror #{50-p}")
    empty=True
    for i,ps in enumerate(P):
        need=[i]+([i+1] if ps[-1]>18 else [])
        miss=[w for w in need if w not in reg['d']]
        if miss: load([miss[0]]+([miss[0]+1] if miss[0]+1<len(P) and len(free['d'])>=2 else []))
        for p in ps:
            field('r11','d',i,p);field('r12','s',i,p)
            if sub: A("sub r12,r11,r12");A("add r12,r12,r3")     # v = a - b + black
            else: A("add r12,r11,r12");A("sub r12,r12,r3")       # v = a + b - black
            A("cmp r12,r4");A("bichi r12,r4,r12,asr #31")        # v<0 -> 0, v>w -> w (unsigned compare)
            A("cmp r11,r4");A("movhs r12,r11")                   # a >= w: stays
            if p<=18:
                sh=18-p
                if empty: A(f"mov lr,r12,lsl #{sh}" if sh else "mov lr,r12");empty=False
                else: A(f"orr lr,lr,r12,lsl #{sh}" if sh else "orr lr,lr,r12")
            else:
                A(f"orr lr,lr,r12,lsr #{p-18}")
                A("mov lr,lr,ror #16");A(f"str lr,[r0,#{4*i-off}]")
                A(f"mov lr,r12,lsl #{50-p}")
        if ps[-1]<=18: A("mov lr,lr,ror #16");A(f"str lr,[r0,#{4*i-off}]")
        for b in ('d','s'): free[b].append(reg[b].pop(i))
    assert off==28
    A("ldr r11,[sp]");A("cmp r0,r11");A("bne 1b")
    A("add sp,sp,#4")
    A("9:");A("pop {r4-r11,pc}")
    return L
def fn(name,L):
    body="\n".join('        "'+l+'\\n"' for l in L)
    return 'static __attribute__((naked,noinline,unused)) void '+name+'(uint32_t *d,const uint32_t *s,unsigned pairs,\n    unsigned black,unsigned white)\n{\n    asm volatile(\n'+body+'\n    );\n}\n'
src='''/* LCM65 Live Bulb kernels in ARM assembly (ARMv5TE, ARM state).
 * lc_raw14_add_ldm: same result as lc_raw14_add_sel (acc = acc + frame -
 * black, clamped to [0, white], a sample at or above white stays), bit for
 * bit; lc_raw14_sub_ldm likewise for lc_raw14_sub_sel (dark frames).
 * Per field like the C word kernel, with three differences:
 *  - words loaded with LDM, two at a time (4 + 3 per buffer per pair; the
 *    LCB2 benchmark: both buffers read in 0.92 s with LDM, ~1.25 s word by
 *    word); stores address back from the advanced pointer;
 *  - no rotation of the input words: an inner field is one AND of F with
 *    the native word rotated (ror16 and the field shift in one), a field
 *    that crosses a word one AND of the low half of W and the high half of
 *    N put together (MOV, ORR);
 *  - the clamp to [0, w] is one unsigned CMP and BICHI w, v ASR #31.
 * Generated by build_tools/gen_raw14_add_asm.py; checked bit-exact against
 * the C kernels as machine code on an ARM interpreter by
 * test_livecomp_raw14_add_asm.py. Camera build only; host builds use the C
 * kernels. 4-byte alignment, pairs of blocks. */
#ifndef LIVECOMP_RAW14_ADD_ASM_H
#define LIVECOMP_RAW14_ADD_ASM_H
#include <stdint.h>
#if defined(__ARM__) || defined(__arm__)
'''+fn('lc_raw14_add_ldm',gen(False))+fn('lc_raw14_sub_ldm',gen(True))+'''#endif
#endif
'''
import pathlib
out=pathlib.Path(__file__).resolve().parents[1]/'modules/livecomp/raw14-add-asm.h'
out.write_text(src,newline='\n');print('wrote',out)
